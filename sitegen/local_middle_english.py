def individualize_local_middle_english_body(body: str, slug: str) -> str:
    """Replace imported boilerplate for the 69 local middle-English pages."""
    if not is_local_middle_english_slug(slug):
        return body
    if f'data-content-version="{CONTENT_VERSION}"' in body:
        return body
    focus = LOCAL_MIDDLE_ENGLISH_FOCUS.get(slug, _focus_from_body(body))
    return build_local_middle_english_body(slug, focus)
