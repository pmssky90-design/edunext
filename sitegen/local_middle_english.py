    focus = LOCAL_MIDDLE_ENGLISH_FOCUS.get(slug, "학교 영어 자료의 근거 확인하기")
    kind = _kind_for(focus)
    if slug in LOCAL_MIDDLE_ENGLISH_ORDER:
        index = LOCAL_MIDDLE_ENGLISH_ORDER.index(slug)
    else:
        index = _stable_number(slug) % len(META_TITLE_FRAMES)
    title_focus = re.sub(r"(?<!\S)영어(?=\s)", "", focus)
    title_focus = re.sub(r"\s+", " ", title_focus).strip()
    search_title = META_TITLE_FRAMES[index % len(META_TITLE_FRAMES)].format(
        slug=slug,
        focus=title_focus,
    )
    description = META_DESCRIPTION_FRAMES[kind][
        (index * 3 + index // len(META_DESCRIPTION_FRAMES[kind]))
        % len(META_DESCRIPTION_FRAMES[kind])
    ].format(slug=slug, focus=focus)
    return search_title, description


