def _plain(value: str) -> str:
    return re.sub(r"\s+", " ", unescape(re.sub(r"<[^>]+>", " ", value))).strip()


def _focus_from_body(body: str) -> str:
    first_heading = re.search(r"<h2\b[^>]*>(.*?)</h2>", body, flags=re.I | re.S)
    if not first_heading:
        return "학교 영어 자료의 근거 확인하기"
    heading = _plain(first_heading.group(1))
    match = re.search(r",\s*(.+?)를 중심으로", heading)
    if match:
        return match.group(1).strip()
    return "학교 영어 자료의 근거 확인하기"


def _kind_for(focus: str) -> str:
    if any(word in focus for word in ("듣기", "대화", "발음", "말하기")):
        return "listening"
    if any(word in focus for word in ("쓰기", "서술형", "영작", "발표", "답하기")):
        return "output"
    if any(
        word in focus
        for word in (
            "문법",
            "시제",
            "부정사",
            "동명사",
            "분사",
            "관계대명사",
            "조동사",
            "수동태",
            "주어와 동사",
            "어순",
            "문장 구조",
            "수식어구",
            "대명사",
        )
    ):
        return "grammar"
    if any(
        word in focus
        for word in (
            "독해",
            "문단",
            "핵심어",
            "실용문",
            "도표",
            "안내문",
            "중심 문장",
            "글의 목적",
            "제목",
            "빈칸",
            "내용 일치",
            "순서 배열",
            "문장 삽입",
            "요약문",
            "문해력",
        )
    ):
        return "reading"
    return "routine"


