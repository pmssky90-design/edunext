def _plain_text(value: str) -> str:
    return re.sub(r"\s+", " ", unescape(re.sub(r"<[^>]+>", " ", value))).strip()


def _remove_generic_sections(body: str, slug: str) -> str:
    headings_to_remove = GENERIC_HEADINGS_TO_REMOVE | PAGE_HEADINGS_TO_REMOVE.get(slug, set())

    def keep_or_remove(match: re.Match[str]) -> str:
        label = _plain_text(match.group(1))
        remove = label in headings_to_remove or label.startswith(f"{slug},")
        return "" if remove else match.group(0)

    return re.sub(
        r"<h2\b[^>]*>(.*?)</h2>.*?(?=<h2\b|$)",
        keep_or_remove,
        body,
        flags=re.I | re.S,
    )


