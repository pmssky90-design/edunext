def _replace_scenario(body: str, slug: str) -> str:
    replaced = False

    def replace(match: re.Match[str]) -> str:
        nonlocal replaced
        section = match.group(0)
        if replaced:
            return section
        if 'class="scenario-notice"' in section or "이 변화는 점수 보장이 아니라" in section:
            replaced = True
            return _secondary_scenario(slug)
        return section

    updated = re.sub(r"<h2\b[^>]*>.*?</h2>.*?(?=<h2\b|$)", replace, body, flags=re.I | re.S)
    return updated if replaced else f"{_secondary_scenario(slug)}\n{body}"


